"""Writes vorbis_setups.gen.h: Vorbis setup (codebook) header packets for the encoder settings the game's
FSB5 sounds name by id. FSB5 stores only a 32-bit id of the setup header, not the header itself; the id is
the CRC-32 of the setup packet that libvorbis (BSD licence) writes for those settings, so we regenerate it
with the system libvorbisenc. Every sound in the game uses one setting: stereo, 48 kHz, quality 0.3.

Run: python3 make_vorbis_setups.py   (needs libvorbisenc.so.2 and libvorbis.so.0, version 1.3.7)
"""
import ctypes
import zlib

SETTINGS = [(2, 48000, 0.3)]  # (channels, rate, quality) seen in the game's banks
EXPECTED = {(2, 48000, 0.3): 0xC4C30A29}

venc = ctypes.CDLL("libvorbisenc.so.2")
vorbis = ctypes.CDLL("libvorbis.so.0")


class Packet(ctypes.Structure):
    _fields_ = [("packet", ctypes.POINTER(ctypes.c_ubyte)), ("bytes", ctypes.c_long), ("b_o_s", ctypes.c_long),
                ("e_o_s", ctypes.c_long), ("granulepos", ctypes.c_int64), ("packetno", ctypes.c_int64)]


def header_packets(channels, rate, quality):
    info = ctypes.create_string_buffer(4096)
    comment = ctypes.create_string_buffer(4096)
    dsp = ctypes.create_string_buffer(65536)
    vorbis.vorbis_info_init(info)
    assert venc.vorbis_encode_init_vbr(info, channels, rate, ctypes.c_float(quality)) == 0
    vorbis.vorbis_comment_init(comment)
    assert vorbis.vorbis_analysis_init(dsp, info) == 0
    packets = [Packet(), Packet(), Packet()]
    vorbis.vorbis_analysis_headerout(dsp, comment, *[ctypes.byref(p) for p in packets])
    out = [bytes(ctypes.string_at(p.packet, p.bytes)) for p in packets]
    vorbis.vorbis_dsp_clear(dsp)
    vorbis.vorbis_comment_clear(comment)
    vorbis.vorbis_info_clear(info)
    return out


def main():
    lines = ["// Generated by make_vorbis_setups.py from libvorbis 1.3.7 (BSD). Do not edit.",
             "#pragma once", "#include <cstddef>", "#include <cstdint>", "", "namespace fsb {", ""]
    entries = []
    for i, (channels, rate, quality) in enumerate(SETTINGS):
        ident, _, setup = header_packets(channels, rate, quality)
        crc = zlib.crc32(setup) & 0xFFFFFFFF
        assert crc == EXPECTED[(channels, rate, quality)], hex(crc)
        short_log, long_log = ident[28] & 15, ident[28] >> 4
        lines.append("static const uint8_t vorbis_setup_%d[%d] = {" % (i, len(setup)))
        for at in range(0, len(setup), 24):
            lines.append("\t" + ", ".join("0x%02x" % b for b in setup[at:at + 24]) + ",")
        lines.append("};")
        # libvorbisenc writes two modes: 0 short block, 1 long block.
        entries.append("\t{0x%08xu, %d, %d, %d, %d, vorbis_setup_%d, sizeof(vorbis_setup_%d)}," %
                       (crc, channels, rate, 1 << short_log, 1 << long_log, i, i))
    lines += ["", "struct VorbisSetup {", "\tuint32_t id;", "\tint channels;", "\tint rate;", "\tint short_block;",
              "\tint long_block;", "\tconst uint8_t *packet;", "\tsize_t size;", "};", "",
              "static const VorbisSetup vorbis_setups[] = {"] + entries + ["};", "", "} // namespace fsb", ""]
    open("vorbis_setups.gen.h", "w").write("\n".join(lines))
    print("wrote vorbis_setups.gen.h with", len(entries), "setup(s)")


if __name__ == "__main__":
    main()
