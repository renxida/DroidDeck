#!/usr/bin/env python3
"""Writes Cards.g.cs: 1200 distinct ordinary C# methods the frame loop calls for the first time in batches,
standing in for game code reached when new content loads (a new room, card or enemy). Unlike the expression
lambdas, these live in Bench.dll, so ReadyToRun can precompile them. Deterministic: same file every run."""
import sys

N = 1200
out = ["// Generated by gen_cards.py. Do not edit.", "static partial class Cards", "{"]
for i in range(N):
    a, b, c = 3 + i % 17, 5 + (i * 7) % 23, 1 + (i * 13) % 11
    kind = i % 4
    if kind == 0:
        body = f"int s = x; for (int k = 0; k < {8 + i % 9}; k++) s = s * {a} + (k ^ {b}); return s;"
    elif kind == 1:
        body = (f"switch ((x + {c}) % 5) {{ case 0: return x * {a}; case 1: return x - {b}; "
                f"case 2: return (x << {c % 5}) ^ {b}; case 3: return x / {c} + {a}; default: return ~x + {i}; }}")
    elif kind == 2:
        body = (f"var arr = new int[{4 + i % 12}]; for (int k = 0; k < arr.Length; k++) arr[k] = x + k * {a}; "
                f"int s = 0; foreach (var v in arr) s += v % {b + 1}; return s;")
    else:
        body = f"double d = x * {a}.5; d = d / {c}.25 + {b}; return (int)(d * d) ^ {i};"
    out.append(f"    static int C{i}(int x) {{ {body} }}")
out.append(f"    public const int Count = {N};")
out.append("    public static readonly System.Func<int, int>[] All = {")
out.append("        " + ", ".join(f"C{i}" for i in range(N)))
out.append("    };")
out.append("}")
open(sys.argv[1] if len(sys.argv) > 1 else "Cards.g.cs", "w").write("\n".join(out) + "\n")
